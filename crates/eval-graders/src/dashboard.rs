//! Read-only static dashboard: one self-contained HTML file rendered
//! from a `PortfolioReport` (canonical stores, no shadow database).
//!
//! No frameworks, no network, no JS dependencies: inline CSS plus a
//! small vanilla filter script. Tables carry `data-*` attributes so
//! the project/suite/status/time filters never drop rows silently —
//! filtering only hides, and a live count states what is shown.

use crate::portfolio::{PortfolioReport, SuiteRefReport};
use std::fmt::Write as _;

/// Render the full dashboard page.
pub fn render_portfolio(report: &PortfolioReport) -> String {
    let mut html = String::new();
    html.push_str("<!DOCTYPE html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n");
    html.push_str(
        "<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n<title>",
    );
    html.push_str(&esc(&report.workspace_name));
    html.push_str(" — eval dashboard</title>\n<style>\n");
    html.push_str(CSS);
    html.push_str("\n</style>\n</head>\n<body>\n");
    render_header(&mut html, report);
    render_overview(&mut html, report);
    for project in &report.projects {
        render_project(&mut html, project);
    }
    html.push_str(
        "<footer><p>Generated by <code>eval dashboard</code> from canonical run stores. ",
    );
    html.push_str("Metrics marked n/a were never recorded — never zero-filled.</p></footer>\n");
    html.push_str("<script>\n");
    html.push_str(JS);
    html.push_str("\n</script>\n</body>\n</html>\n");
    html
}

fn render_header(html: &mut String, report: &PortfolioReport) {
    let _ = writeln!(
        html,
        "<header><h1>{}</h1><p>eval portfolio dashboard · generated {}</p></header>",
        esc(&report.workspace_name),
        esc(&format_ms(report.generated_at_ms)),
    );
    let t = &report.totals;
    let rate = t
        .pass_rate()
        .map(|r| format!("{:.1}%", r * 100.0))
        .unwrap_or_else(|| "n/a".to_string());
    let _ = writeln!(
        html,
        "<section class=\"totals\" aria-label=\"Portfolio totals\">\
        <div><strong>{}</strong><span>projects ({}/{})</span></div>\
        <div><strong>{}</strong><span>suites with runs (of {})</span></div>\
        <div><strong>{}</strong><span>overall pass rate</span></div>\
        <div><strong>{}</strong><span>cases passed</span></div>\
        <div><strong>{}</strong><span>cases failed</span></div>\
        <div><strong>{}</strong><span>infra errors</span></div>\
        <p class=\"note\">{}</p></section>",
        t.projects_total,
        t.projects_available,
        t.projects_total,
        rate,
        t.suites_with_runs,
        t.suites_total,
        t.cases_passed,
        t.cases_failed,
        t.cases_infra,
        esc(&t.pass_rate_note),
    );
}

fn render_overview(html: &mut String, report: &PortfolioReport) {
    html.push_str("<section aria-label=\"Portfolio overview\"><h2>Projects</h2>");
    html.push_str("<div class=\"filters\">");
    html.push_str("<label>Project <select id=\"f-project\"><option value=\"\">all</option>");
    for project in &report.projects {
        let _ = writeln!(
            html,
            "<option value=\"{}\">{}</option>",
            esc(&project.id),
            esc(&project.name)
        );
    }
    html.push_str("</select></label>");
    html.push_str(
        "<label>Status <select id=\"f-status\"><option value=\"\">all</option>\
        <option value=\"pass\">pass</option><option value=\"fail\">fail</option>\
        <option value=\"error\">error</option><option value=\"unavailable\">unavailable</option>\
        <option value=\"no-runs\">no runs</option></select></label>",
    );
    html.push_str(
        "<label>Suite <input id=\"f-suite\" type=\"search\" placeholder=\"filter suites\"></label>",
    );
    html.push_str("<label>Since <input id=\"f-since\" type=\"date\"></label>");
    html.push_str("<p id=\"filter-count\" role=\"status\"></p></div>");
    html.push_str("<table><thead><tr><th>Project</th><th>Status</th><th>Latest run</th><th>Cases</th><th>Regression</th><th>Coverage</th><th>Last success / failure</th></tr></thead><tbody>");
    for project in &report.projects {
        let (status, status_class) = project_status(project);
        let latest = latest_run_text(project);
        let regression = regression_text(project);
        let coverage = format!(
            "{} suites, {} cases",
            project.suites.len(),
            project.cases_total
        );
        let last = format!(
            "{} / {}",
            project
                .last_success_ms
                .map(format_ms)
                .unwrap_or_else(|| "never".to_string()),
            project
                .last_failure_ms
                .map(format_ms)
                .unwrap_or_else(|| "never".to_string())
        );
        let since = project
            .history
            .first()
            .map(|h| h.started_at_ms / 86_400_000)
            .unwrap_or(0);
        let _ = writeln!(
            html,
            "<tr data-project=\"{}\" data-status=\"{}\" data-since=\"{}\" data-suite=\"{}\">\
            <td><a href=\"#project-{}\">{}<br><small>{}</small></a></td>\
            <td><span class=\"badge {}\">{}</span></td><td>{}</td>\
            <td>{} pass / {} fail / {} infra</td><td>{}</td><td>{}</td><td>{}</td></tr>",
            esc(&project.id),
            status_class,
            since,
            esc(&project
                .suites
                .iter()
                .map(|s| s.suite_id.as_str())
                .collect::<Vec<_>>()
                .join(" ")),
            esc(&project.id),
            esc(&project.name),
            esc(&project.id),
            status_class,
            status,
            latest,
            project.cases_passed,
            project.cases_failed,
            project.cases_infra,
            regression,
            esc(&coverage),
            esc(&last),
        );
    }
    html.push_str("</tbody></table></section>");
}

fn render_project(html: &mut String, project: &crate::portfolio::ProjectReport) {
    let _ = writeln!(
        html,
        "<section id=\"project-{}\" aria-label=\"Project {}\">",
        esc(&project.id),
        esc(&project.name)
    );
    let _ = writeln!(
        html,
        "<h2>{} <small>{}</small></h2>",
        esc(&project.name),
        esc(&project.id)
    );
    if !project.available {
        let _ = writeln!(
            html,
            "<p class=\"unavailable\">Unavailable: {}</p></section>",
            esc(project
                .unavailability
                .as_deref()
                .unwrap_or("unknown reason"))
        );
        return;
    }
    if project.suites.is_empty() {
        html.push_str("<p class=\"empty\">No suites registered for this project yet.</p>");
    }
    for suite in &project.suites {
        let _ = writeln!(
            html,
            "<h3 data-suite-name=\"{}\">Suite <code>{}</code> <small>{}</small></h3>",
            esc(&suite.suite_id),
            esc(&suite.suite_id),
            esc(&suite.suite_path)
        );
        if !suite.available {
            let _ = writeln!(
                html,
                "<p class=\"unavailable\">{}</p>",
                esc(suite.note.as_deref().unwrap_or("suite unavailable"))
            );
            continue;
        }
        match &suite.regression {
            Some(true) => html.push_str("<p class=\"regressed\">Regressed vs baseline. "),
            Some(false) => html.push_str("<p class=\"clean\">Clean vs baseline. "),
            None => html.push_str("<p class=\"nobase\">No regression claim. "),
        }
        html.push_str(&esc(suite.regression_note.as_deref().unwrap_or("")));
        html.push_str("</p>");
        if suite.refs.is_empty() {
            html.push_str("<p class=\"empty\">No runs recorded for this suite yet.</p>");
            continue;
        }
        html.push_str("<table><thead><tr><th>Ref</th><th>Run</th><th>Started</th><th>Code</th><th>Result</th><th>Cases</th><th>Latency p50/p95 (n)</th><th>Tokens / cost</th><th>Artifacts</th></tr></thead><tbody>");
        for r in &suite.refs {
            render_ref_row(html, &project.id, &suite.suite_id, r);
        }
        html.push_str("</tbody></table>");
        for r in &suite.refs {
            if r.load_error.is_some() {
                continue;
            }
            for failed in &r.failed_cases {
                let _ = writeln!(
                    html,
                    "<details><summary>Failed case <code>{}</code> [{}]</summary><ul>",
                    esc(&failed.case_id),
                    esc(&failed.statuses.join(", "))
                );
                for reason in &failed.reasons {
                    let _ = writeln!(html, "<li>{}</li>", esc(reason));
                }
                html.push_str("</ul></details>");
            }
        }
        if !suite.history.is_empty() {
            html.push_str("<details><summary>History</summary><table><thead><tr><th>Ref</th><th>Run</th><th>Started</th><th>Result</th><th>Rate</th></tr></thead><tbody>");
            for h in &suite.history {
                let mark = if h.pass { "pass" } else { "fail" };
                let _ = writeln!(
                    html,
                    "<tr><td>{}</td><td><code>{}</code></td><td>{}</td>\
                    <td><span class=\"badge {}\">{}</span></td><td>{:.0}%</td></tr>",
                    esc(&h.ref_name),
                    esc(&h.run_id),
                    esc(&format_ms(h.started_at_ms)),
                    mark,
                    mark,
                    h.pass_rate * 100.0
                );
            }
            html.push_str("</tbody></table></details>");
        }
    }
    render_usage(html, project);
    html.push_str("</section>");
}

fn render_usage(html: &mut String, project: &crate::portfolio::ProjectReport) {
    html.push_str("<h3>LLM usage</h3>");
    let Some(view) = &project.usage else {
        html.push_str("<p class=\"empty\">No usage events recorded yet.</p>");
        return;
    };
    let contexts = [
        ("production", &view.production),
        ("benchmark", &view.benchmark),
        ("dev", &view.dev),
    ];
    let mut any = false;
    for (name, usage) in contexts {
        let Some(usage) = usage else { continue };
        if usage.events == 0 {
            continue;
        };
        any = true;
        let _ = writeln!(
            html,
            "<h4 data-usage-context=\"{name}\">Usage — {name} ({} events, {} calls, {} requests)</h4>",
            usage.events, usage.calls, usage.requests,
        );
        html.push_str("<table><thead><tr><th>Model</th><th>Origin</th><th>Calls</th><th>Success</th><th>Tokens in/out</th><th>Cost reported/est.</th><th>Latency p50/p95</th><th>Errors</th></tr></thead><tbody>");
        for row in &usage.by_model {
            let _ = writeln!(
                html,
                "<tr data-project=\"{}\" data-status=\"usage\">\
                <td>{}:{}</td><td>{}</td><td>{}</td><td>{}</td><td>{} / {}</td>\
                <td>{} / {}</td><td>{}</td><td>{}e {}t {}r</td></tr>",
                esc(&project.id),
                esc(&row.provider),
                esc(&row.model),
                esc(&row.origin),
                row.calls,
                row.success_rate
                    .map_or("n/a".to_string(), |r| format!("{:.0}%", r * 100.0)),
                fmt_opt(&row.input_tokens.value),
                fmt_opt(&row.output_tokens.value),
                fmt_usd(&row.reported_usd.value),
                fmt_usd_est(&row.estimated_usd.value, &row.pricing_version),
                fmt_lat(&row.latency),
                row.errors,
                row.timeouts,
                row.retries,
            );
        }
        html.push_str("</tbody></table>");
    }
    if !any {
        html.push_str("<p class=\"empty\">No usage events recorded yet.</p>");
    }
    if view.has_legacy_ai {
        html.push_str("<p class=\"note\">Run views may also show legacy result-attached usage; those aggregates are shown with their runs only and are never added to the event totals above.</p>");
    }
    if !view.comparisons.is_empty() {
        html.push_str("<h4>Benchmark comparison</h4>");
        html.push_str("<p class=\"note\">Same tasks, same graders per tag. Rows labeled synthetic are fixture demonstrations, not model evidence. Costs show provenance and pricing version.</p>");
        html.push_str("<table><thead><tr><th>Variant</th><th>Quality (judge mean, n)</th><th>Calls</th><th>Tokens in/out</th><th>Est. cost</th><th>Latency p50/p95</th><th>Origins</th><th>Errors</th></tr></thead><tbody>");
        for row in &view.comparisons {
            let _ = writeln!(
                html,
                "<tr data-project=\"{}\" data-status=\"usage\">\
                <td><code>{}</code><br><small>{}:{} {}</small></td>\
                <td>{}</td><td>{}</td><td>{} / {}</td><td>{}</td><td>{}</td><td>{}</td><td>{}</td></tr>",
                esc(&project.id),
                esc(&row.tag),
                esc(&row.suite),
                esc(&row.ref_name),
                esc(&row.run_id[..row.run_id.len().min(13)]),
                row.quality.map_or("n/a".to_string(), |q| format!(
                    "{q:.2} (n={})",
                    row.quality_n
                )),
                row.calls,
                fmt_opt(&row.input_tokens.value),
                fmt_opt(&row.output_tokens.value),
                fmt_usd_est(&row.estimated_usd.value, &row.pricing_version),
                fmt_lat(&row.latency),
                esc(&row.origins.join(", ")),
                row.errors,
            );
        }
        html.push_str("</tbody></table>");
    }
}

fn fmt_opt(value: &Option<f64>) -> String {
    match value {
        Some(v) => format!("{v:.0}"),
        None => "n/a".to_string(),
    }
}

fn fmt_usd(value: &Option<f64>) -> String {
    match value {
        Some(v) => format!("${v:.4} reported"),
        None => "n/a".to_string(),
    }
}

fn fmt_usd_est(value: &Option<f64>, version: &Option<u32>) -> String {
    match (value, version) {
        (Some(v), Some(ver)) => format!("${v:.4} est (pricing v{ver})"),
        (Some(v), None) => format!("${v:.4} est"),
        _ => "n/a".to_string(),
    }
}

fn fmt_lat(latency: &Option<eval_usage::LatencyDist>) -> String {
    match latency {
        Some(l) => format!("{}ms / {}ms (n={})", l.p50_ms, l.p95_ms, l.n),
        None => "n/a".to_string(),
    }
}

fn render_ref_row(html: &mut String, project_id: &str, suite_id: &str, r: &SuiteRefReport) {
    if let Some(error) = &r.load_error {
        let _ = writeln!(
            html,
            "<tr data-project=\"{}\" data-status=\"error\" data-since=\"0\" data-suite=\"{}\">\
            <td>{}</td><td><code>{}</code></td><td colspan=\"6\">Unreadable run record: {}</td></tr>",
            esc(project_id),
            esc(suite_id),
            esc(&r.ref_name),
            esc(&r.run_id),
            esc(error)
        );
        return;
    }
    let (mark, class) = if r.pass {
        ("pass", "pass")
    } else {
        ("fail", "fail")
    };
    let latency = r.latency.as_ref().map_or_else(
        || "n/a".to_string(),
        |l| format!("{}ms / {}ms ({})", l.p50_ms, l.p95_ms, l.n),
    );
    let tokens = if r.tokens.reporting_trials == 0 {
        format!("n/a (0/{} trials reported usage)", r.tokens.total_trials)
    } else {
        format!(
            "in {} / out {} / ${} ({} / {} trials)",
            r.tokens
                .tokens_in
                .map_or("n/a".to_string(), |v| v.to_string()),
            r.tokens
                .tokens_out
                .map_or("n/a".to_string(), |v| v.to_string()),
            r.tokens
                .cost_usd
                .map_or("n/a".to_string(), |v| format!("{v:.4}")),
            r.tokens.reporting_trials,
            r.tokens.total_trials
        )
    };
    let artifacts = format!(
        "<a href=\"{}\">metadata</a> · <a href=\"{}\">observations</a> · <a href=\"{}\">grades</a>",
        esc(&file_uri(&format!("{}/metadata.json", r.run_dir))),
        esc(&file_uri(&format!("{}/observations.jsonl", r.run_dir))),
        esc(&file_uri(&format!("{}/grades.json", r.run_dir))),
    );
    let _ = writeln!(
        html,
        "<tr data-project=\"{}\" data-status=\"{}\" data-since=\"{}\" data-suite=\"{}\">\
        <td>{}</td><td><code>{}</code></td><td>{}</td><td><code>{}</code></td>\
        <td><span class=\"badge {}\">{}</span> {:.0}%</td>\
        <td>{} ({} pass)</td><td>{}</td><td>{}</td><td>{}</td></tr>",
        esc(project_id),
        class,
        r.started_at_ms / 86_400_000,
        esc(suite_id),
        esc(&r.ref_name),
        esc(&r.run_id),
        esc(&format_ms(r.started_at_ms)),
        esc(&short_sha(&r.code_version)),
        class,
        mark,
        r.pass_rate * 100.0,
        r.cases_total,
        r.cases_passed,
        esc(&latency),
        esc(&tokens),
        artifacts,
    );
}

fn project_status(project: &crate::portfolio::ProjectReport) -> (String, &'static str) {
    if !project.available {
        return ("unavailable".to_string(), "unavailable");
    }
    let any_runs = project.cases_total > 0 || project.suites.iter().any(|s| !s.refs.is_empty());
    if !any_runs {
        return ("no runs".to_string(), "no-runs");
    }
    if project.cases_infra > 0 {
        return ("error".to_string(), "error");
    }
    if project.cases_failed > 0 {
        return ("fail".to_string(), "fail");
    }
    ("pass".to_string(), "pass")
}

fn latest_run_text(project: &crate::portfolio::ProjectReport) -> String {
    match project.history.first() {
        Some(h) => format!(
            "{}:{} {} ({})",
            h.suite,
            h.ref_name,
            &h.run_id[..h.run_id.len().min(13)],
            if h.pass { "pass" } else { "fail" }
        ),
        None => "none".to_string(),
    }
}

fn regression_text(project: &crate::portfolio::ProjectReport) -> String {
    let mut regressed = 0;
    let mut clean = 0;
    for suite in &project.suites {
        match suite.regression {
            Some(true) => regressed += 1,
            Some(false) => clean += 1,
            None => {}
        }
    }
    if regressed > 0 {
        format!("{regressed} regressed")
    } else if clean > 0 {
        format!("{clean} clean")
    } else {
        "no baseline".to_string()
    }
}

fn short_sha(version: &str) -> String {
    if version.len() > 12 {
        version[..12].to_string()
    } else {
        version.to_string()
    }
}

fn format_ms(ms: u64) -> String {
    if ms == 0 {
        return "n/a".to_string();
    }
    let (y, m, d) = ymd(ms / 86_400_000);
    format!("{y:04}-{m:02}-{d:02}")
}

/// Days-since-epoch to civil date (Howard Hinnant's algorithm).
fn ymd(days: u64) -> (i64, u32, u32) {
    let z = days as i64 + 719_468;
    let era = z.div_euclid(146_097);
    let doe = z.rem_euclid(146_097);
    let yoe = (doe - doe / 1_460 + doe / 36_524 - doe / 146_096) / 365;
    let y = yoe + era * 400;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let d = (doy - (153 * mp + 2) / 5 + 1) as u32;
    let m = (if mp < 10 { mp + 3 } else { mp - 9 }) as u32;
    (if m <= 2 { y + 1 } else { y }, m, d)
}

fn file_uri(path: &str) -> String {
    let normalized = path.replace('\\', "/");
    // Percent-encode everything outside the unreserved set so spaces
    // and quotes in repo paths cannot break the href attribute.
    let mut encoded = String::with_capacity(normalized.len());
    for byte in normalized.bytes() {
        match byte {
            b'A'..=b'Z' | b'a'..=b'z' | b'0'..=b'9' | b'-' | b'_' | b'.' | b'~' | b'/' | b':' => {
                encoded.push(byte as char);
            }
            _ => {
                encoded.push_str(&format!("%{byte:02X}"));
            }
        }
    }
    if encoded.starts_with('/') {
        format!("file://{encoded}")
    } else {
        format!("file:///{encoded}")
    }
}

/// Minimal HTML escaper (text + attribute contexts).
pub fn esc(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    for c in text.chars() {
        match c {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '"' => out.push_str("&quot;"),
            _ => out.push(c),
        }
    }
    out
}

